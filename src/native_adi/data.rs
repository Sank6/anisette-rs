const fn decode8<const N: usize>(mut data: [u8; N], mut seed: u32) -> [u8; N] {
    let mut i = 0;
    while i < N {
        seed ^= seed << 13;
        seed ^= seed >> 17;
        seed ^= seed << 5;
        data[i] ^= seed as u8;
        i += 1;
    }
    data
}

const fn decode32<const N: usize>(mut data: [u32; N], mut seed: u32) -> [u32; N] {
    let mut i = 0;
    while i < N {
        seed ^= seed << 13;
        seed ^= seed >> 17;
        seed ^= seed << 5;
        data[i] ^= seed;
        i += 1;
    }
    data
}

